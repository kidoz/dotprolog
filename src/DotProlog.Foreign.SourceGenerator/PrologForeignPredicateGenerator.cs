using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace DotProlog.Foreign.SourceGenerator;

/// <summary>Generates static registration tables for attributed foreign predicates.</summary>
[Generator(LanguageNames.CSharp)]
public sealed class PrologForeignPredicateGenerator : IIncrementalGenerator
{
    private const string AttributeName = "DotProlog.Runtime.PrologPredicateAttribute";
    private const string ContextName = "DotProlog.Runtime.PrologContext";
    private const string CellName = "DotProlog.Runtime.Cell";

    private static readonly DiagnosticDescriptor InvalidSignature = new(
        "DPL4001",
        "Invalid foreign predicate signature",
        "{0}",
        "DotProlog.Foreign",
        DiagnosticSeverity.Error,
        isEnabledByDefault: true
    );

    private static readonly DiagnosticDescriptor InvalidDeclaration = new(
        "DPL4002",
        "Invalid foreign predicate declaration",
        "{0}",
        "DotProlog.Foreign",
        DiagnosticSeverity.Error,
        isEnabledByDefault: true
    );

    private static readonly DiagnosticDescriptor DuplicateRegistration = new(
        "DPL4003",
        "Duplicate foreign predicate registration",
        "Foreign predicate '{0}' is registered by more than one method",
        "DotProlog.Foreign",
        DiagnosticSeverity.Error,
        isEnabledByDefault: true
    );

    private static readonly DiagnosticDescriptor UnsupportedDeterminism = new(
        "DPL4004",
        "Unsupported foreign predicate determinism",
        "Foreign predicate determinism '{0}' is not supported; only 'det' is available",
        "DotProlog.Foreign",
        DiagnosticSeverity.Error,
        isEnabledByDefault: true
    );

    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var candidates = context.SyntaxProvider.ForAttributeWithMetadataName(
            AttributeName,
            static (node, _) => node is MethodDeclarationSyntax,
            static (attributeContext, cancellationToken) => Candidate.Create(attributeContext, cancellationToken)
        );

        context.RegisterSourceOutput(candidates.Collect(), static (output, methods) => Emit(output, methods));
    }

    private static void Emit(SourceProductionContext context, IEnumerable<Candidate> candidates)
    {
        List<Candidate> valid = [];
        foreach (var candidate in candidates)
        {
            if (candidate.Diagnostic is not null)
            {
                context.ReportDiagnostic(candidate.Diagnostic);
            }
            else
            {
                valid.Add(candidate);
            }
        }

        foreach (var duplicate in valid.GroupBy(candidate => candidate.Identity).Where(group => group.Count() > 1))
        {
            foreach (var candidate in duplicate)
            {
                context.ReportDiagnostic(Diagnostic.Create(DuplicateRegistration, candidate.Location, duplicate.Key));
                candidate.Suppress = true;
            }
        }

        var text = new StringBuilder();
        text.AppendLine("// <auto-generated />");
        text.AppendLine("// Generated by DotProlog.Foreign.SourceGenerator from [PrologPredicate] methods.");
        text.AppendLine("#nullable enable");
        text.AppendLine();
        text.AppendLine("namespace DotProlog.Generated;");
        text.AppendLine();
        text.AppendLine("internal static class ForeignPredicateRegistry");
        text.AppendLine("{");
        text.AppendLine("    internal static void Register(global::DotProlog.Runtime.BuiltinRegistry registry)");
        text.AppendLine("    {");
        text.AppendLine("        global::System.ArgumentNullException.ThrowIfNull(registry);");

        foreach (
            var candidate in valid
                .Where(candidate => !candidate.Suppress)
                .OrderBy(candidate => candidate.Identity, StringComparer.Ordinal)
                .ThenBy(candidate => candidate.Method, StringComparer.Ordinal)
        )
        {
            var registeredName = candidate.Module.Length == 0 ? candidate.Name : candidate.Module + ":" + candidate.Name;
            text.Append("        registry.Register(");
            text.Append(SymbolDisplay.FormatLiteral(registeredName, quote: true));
            text.Append(", ");
            text.Append(candidate.Arity.ToString(System.Globalization.CultureInfo.InvariantCulture));
            text.AppendLine(", static machine =>");
            text.AppendLine("        {");
            text.AppendLine("            var context = new global::DotProlog.Runtime.PrologContext(machine);");
            text.Append("            return ");
            text.Append(candidate.Method);
            text.Append("(ref context");
            for (var argument = 0; argument < candidate.Arity; argument++)
            {
                text.Append(", machine.Argument(");
                text.Append(argument.ToString(System.Globalization.CultureInfo.InvariantCulture));
                text.Append(')');
            }
            text.AppendLine(");");
            text.AppendLine("        });");
        }

        text.AppendLine("    }");
        text.AppendLine("}");
        context.AddSource("DotPrologForeignPredicates.g.cs", SourceText.From(text.ToString(), Encoding.UTF8));
    }

    private sealed class Candidate
    {
        private Candidate(
            string name,
            string module,
            string determinism,
            int arity,
            string method,
            Location location,
            Diagnostic? diagnostic
        )
        {
            Name = name;
            Module = module;
            Determinism = determinism;
            Arity = arity;
            Method = method;
            Location = location;
            Diagnostic = diagnostic;
        }

        internal string Name { get; }

        internal string Module { get; }

        internal string Determinism { get; }

        internal int Arity { get; }

        internal string Method { get; }

        internal string Identity => Module.Length == 0 ? $"{Name}/{Arity}" : $"{Module}:{Name}/{Arity}";

        internal Location Location { get; }

        internal Diagnostic? Diagnostic { get; }

        internal bool Suppress { get; set; }

        internal static Candidate Create(GeneratorAttributeSyntaxContext context, CancellationToken cancellationToken)
        {
            var method = (IMethodSymbol)context.TargetSymbol;
            var attribute = context.Attributes[0];
            var location =
                attribute.ApplicationSyntaxReference?.GetSyntax(cancellationToken).GetLocation()
                ?? method.Locations.FirstOrDefault()
                ?? Location.None;

            var name = NamedString(attribute, "Name") ?? string.Empty;
            var module = NamedString(attribute, "Module") ?? string.Empty;
            var determinism = NamedString(attribute, "Determinism") ?? "det";
            var arity = NamedInt(attribute, "Arity");
            var methodName = method.ContainingType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) + "." + method.Name;

            Diagnostic? diagnostic = null;
            if (!string.Equals(determinism, "det", StringComparison.Ordinal))
            {
                diagnostic = Microsoft.CodeAnalysis.Diagnostic.Create(UnsupportedDeterminism, location, determinism);
            }
            else if (name.Length == 0 || arity is < 0 or > 255)
            {
                diagnostic = Microsoft.CodeAnalysis.Diagnostic.Create(
                    InvalidDeclaration,
                    location,
                    "A foreign predicate needs a non-empty Name and an Arity from 0 through 255."
                );
            }
            else if (
                !method.IsStatic
                || method.MethodKind != MethodKind.Ordinary
                || method.IsGenericMethod
                || !IsAccessibleNonGenericType(method.ContainingType)
                || method.ReturnType.SpecialType != SpecialType.System_Boolean
                || method.DeclaredAccessibility is not (Accessibility.Public or Accessibility.Internal)
                || method.Parameters.Length != arity + 1
                || method.Parameters.Length == 0
                || method.Parameters[0].RefKind != RefKind.Ref
                || method.Parameters[0].Type.ToDisplayString() != ContextName
                || method
                    .Parameters.Skip(1)
                    .Any(parameter => parameter.RefKind != RefKind.None || parameter.Type.ToDisplayString() != CellName)
            )
            {
                diagnostic = Microsoft.CodeAnalysis.Diagnostic.Create(
                    InvalidSignature,
                    method.Locations.FirstOrDefault() ?? location,
                    $"Foreign predicate '{method.Name}' must be a non-generic public or internal static bool method with one ref {ContextName} followed by {arity} {CellName} parameters."
                );
            }

            return new Candidate(name, module, determinism, arity, methodName, location, diagnostic);
        }

        private static bool IsAccessibleNonGenericType(INamedTypeSymbol type)
        {
            for (INamedTypeSymbol? current = type; current is not null; current = current.ContainingType)
            {
                if (
                    current.IsGenericType
                    || current.IsFileLocal
                    || current.DeclaredAccessibility is not (Accessibility.Public or Accessibility.Internal)
                )
                {
                    return false;
                }
            }

            return true;
        }

        private static string? NamedString(AttributeData attribute, string name) =>
            attribute.NamedArguments.FirstOrDefault(argument => argument.Key == name).Value.Value as string;

        private static int NamedInt(AttributeData attribute, string name)
        {
            var value = attribute.NamedArguments.FirstOrDefault(argument => argument.Key == name).Value;
            return value.Value is int arity ? arity : 0;
        }
    }
}
